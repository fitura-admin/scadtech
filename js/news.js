const modal = document.querySelector('.news_modal');

const modalDate = modal.querySelector('.news_modal__data p');
const modalTitle = modal.querySelector('.news_modal__title p');
const modalImg = modal.querySelector('.news_modal__img img');
const modalText = modal.querySelector('.news_modal__text p');
const modalArticle = modal.querySelector('.news_modal__article p');
const modalBody = modal.querySelector('.news_modal__body p');
const modalBottom = modal.querySelector('.news_modal__bottom');

// быстрый доступ по id
const newsMap = {};
newsList.forEach(item => {
    newsMap[item.id] = item;
});

// рендер нижних картинок
function renderBottomImages(images) {
    modalBottom.innerHTML = '';

    images.forEach(src => {
        const img = document.createElement('img');
        img.src = src;
        img.alt = '';
        modalBottom.appendChild(img);
    });
}

let news = document.querySelectorAll('.news_block');
if (window.screen.width < 960) {
    news = document.querySelectorAll('.news_block__link__text');
}

for (let el of news) {
    el.onclick = () => {
        const id = el.dataset.id;
        const data = newsMap[id];

        if (!data) return;

        modalDate.textContent = data.date;
        modalTitle.textContent = data.title;
        modalImg.src = data.images[0]; // первая картинка
        modalText.textContent = data.text;
        modalArticle.textContent = data.article;
        modalBody.innerHTML = data.body.replace(/\n/g, '<br>');

        renderBottomImages(data.images);

        modal.classList.add('active');
    }
}

document.querySelector('.close_news_modal').onclick = () => {
    modal.classList.remove('active');
};